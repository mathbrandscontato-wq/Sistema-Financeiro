import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {blank,PIX,validatePix,calculate,metrics,nextMonth,financial,defaults} from '../lib/core.mjs';
import {prepareDocument} from '../lib/document.mjs';
assert.equal(validatePix(PIX,defaults.key),true);
assert.throws(()=>validatePix(PIX.slice(0,-1)+'8',defaults.key));
assert.throws(()=>validatePix(PIX,'wrong'));
assert.equal(nextMonth('2026-01-31'),'2026-02-28');
assert.equal(nextMonth('2028-01-31'),'2028-02-29');
assert.equal(nextMonth('2026-12-31'),'2027-01-31');
const q={...blank(),number:'MB-001',client:'Ricardo Eccel',company:'Vet Silva',issued:'2026-10-09',valid:'2026-11-09',rows:[{description:'Revisão e otimização de conteúdo de blog',qty:'60',unit:'500',mode:'package'}],notes:'Obrigado pela confiança!',settings:defaults};
assert.equal(calculate(q).total,50000);
assert.equal(calculate(q).rows[0].approx,true);
const cents={...q,rows:[{description:'A',qty:'3',unit:'0.1',mode:'unit'},{description:'B',qty:'1',unit:'1.005',mode:'unit'}]};
assert.equal(calculate(cents).total,131);
assert.throws(()=>calculate({...q,rows:[{description:'Excesso',qty:'100000000',unit:'100000000',mode:'unit'}]}));
assert.equal(calculate({...q,discount:'10',discountMode:'percent'}).total,45000);
assert.throws(()=>calculate({...q,discount:'600'}));
const approved={...q,status:'Aprovado',payments:[{cents:15000}]};
assert.equal(financial(approved),'Parcialmente pago');assert.equal(metrics([approved]).receivable,35000);assert.equal(metrics([approved]).received,15000);
assert.equal(metrics([q]).count,0);
const loader=async p=>new Uint8Array(await fs.readFile(new URL('../public'+p,import.meta.url)));
const doc=await prepareDocument(q,loader);assert.equal(doc.pages.length,1);await fs.writeFile('qa/sample.pdf',doc.bytes);
const long={...q,rows:Array.from({length:40},(_,i)=>({description:`Serviço ${i+1}: revisão de texto, identidade visual e estratégia para marcas.`,qty:'1',unit:'99.99',mode:'unit'})),notes:'Condições e observações '.repeat(150),terms:'Aprovação do briefing e pagamento de sinal.',deadline:'15 dias úteis'};
const large=await prepareDocument(long,loader);assert.ok(large.pages.length>2);await fs.writeFile('qa/multipage.pdf',large.bytes);
console.log('PASS: Pix, CRC, centavos, pacote, descontos, datas, métricas, PDF e paginação.');
